# Run INSIDE the container on the offline server.  Installs / builds
# everything the expert-placement benchmark needs from the bundle made by
# make_offline_bundle.sh, without network (pip index disabled):
#
#   bash <bundle>/MoE-Infinity/benchmarks/expert_placement/offline_setup.sh <bundle>
#   source <bundle>/env.sh          # in every new shell afterwards
#
# Steps: ninja (only if missing) -> setuptools-scm (only if missing) ->
# moe-store from source (--no-deps --no-build-isolation; the build itself uses
# MOE_STORE_CSRC from the bundle either way) -> uuid header/lib fallbacks ->
# build moe_infinity._store + _cpu_moe in place (sm_120) -> self-checks.
# Env: SKIP_BUILD=1, MAX_JOBS (default: nproc), EXTS="_store _cpu_moe".
set -euo pipefail

B="$(cd "${1:?usage: offline_setup.sh <bundle dir>}" && pwd)"
REPO="$B/MoE-Infinity"
W="$B/wheels"
test -d "$REPO" && test -d "$B/cutlass/include/cutlass" && test -d "$W" || {
    echo "ERROR: $B does not look like a moe-ep-offline bundle" >&2
    exit 2
}
export PIP_NO_INDEX=1 PIP_FIND_LINKS="$W" PIP_DISABLE_PIP_VERSION_CHECK=1
PY="${PYTHON:-python3}"
say() { echo "[offline_setup] $*"; }

say "python: $($PY -c 'import sys,torch;print(sys.version.split()[0],"torch",torch.__version__,"cuda",torch.version.cuda)')"

if ! $PY -c "import ninja" 2>/dev/null || ! command -v ninja >/dev/null; then
    say "installing ninja from the bundle"
    $PY -m pip install --no-index --find-links "$W" ninja
fi
command -v ninja >/dev/null || export PATH="$($PY -c 'import ninja,os;print(ninja.BIN_DIR)'):$PATH"

if ! $PY -c "import setuptools_scm" 2>/dev/null; then
    say "installing setuptools-scm from the bundle"
    $PY -m pip install --no-index --find-links "$W" setuptools-scm
fi

MS_VER="$(cat "$B/moe-store/.offline-version" 2>/dev/null || echo 0.2.2)"
export MOE_STORE_CSRC="$B/moe-store/moe_store/csrc"
if $PY -c "import moe_store" 2>/dev/null; then
    say "moe-store already importable"
elif SETUPTOOLS_SCM_PRETEND_VERSION="$MS_VER" \
    $PY -m pip install --no-index --no-deps --no-build-isolation "$B/moe-store"; then
    say "moe-store $MS_VER installed from source"
else
    say "WARNING: pip install of moe-store failed; continuing (the build only needs MOE_STORE_CSRC=$MOE_STORE_CSRC)"
fi

# uuid: core/common/generator.h includes <uuid/uuid.h> and _store links -luuid.
if ! echo '#include <uuid/uuid.h>' | ${CXX:-g++} -x c++ -fsyntax-only - 2>/dev/null; then
    say "uuid/uuid.h missing (no uuid-dev): using the bundled header"
    export CPATH="$B/uuid/include${CPATH:+:$CPATH}"
fi
if ! echo 'int main(){}' | ${CXX:-g++} -x c++ - -luuid -o /dev/null 2>/dev/null; then
    so="$(ldconfig -p 2>/dev/null | awk '/libuuid\.so\.1 .*x86-64/{print $NF; exit}')"
    so="${so:-$(ls /lib/x86_64-linux-gnu/libuuid.so.1 /usr/lib/x86_64-linux-gnu/libuuid.so.1 2>/dev/null | head -1)}"
    if [ -z "$so" ]; then
        echo "ERROR: no libuuid.so.1 on this system; _store cannot link -luuid" >&2
        exit 3
    fi
    say "linking -luuid against $so"
    mkdir -p "$B/uuid/lib"
    ln -sf "$so" "$B/uuid/lib/libuuid.so"
    export LIBRARY_PATH="$B/uuid/lib${LIBRARY_PATH:+:$LIBRARY_PATH}"
fi

SCRATCH="$(dirname "$B")"
cat > "$B/env.sh" <<EOF
# generated by offline_setup.sh; source in every new container shell
export PYTHONPATH="$REPO\${PYTHONPATH:+:\$PYTHONPATH}"
export CUTLASS_DIR="$B/cutlass"
export MOE_STORE_CSRC="$MOE_STORE_CSRC"
export TORCH_EXTENSIONS_DIR="$SCRATCH/torch_ext"
export TRITON_CACHE_DIR="$SCRATCH/triton_cache"
export PIP_NO_INDEX=1 PIP_FIND_LINKS="$W"
export PATH="$PATH"
${CPATH:+export CPATH="$CPATH"}
${LIBRARY_PATH:+export LIBRARY_PATH="$LIBRARY_PATH"}
EOF
# shellcheck disable=SC1091
source "$B/env.sh"

if [ "${SKIP_BUILD:-0}" != "1" ]; then
    say "building ${EXTS:-_store _cpu_moe} for sm_120 (this takes a while)"
    (
        cd "$REPO"
        SETUPTOOLS_SCM_PRETEND_VERSION="0.0.0+offline" \
        MOE_ENABLE_SM120="${MOE_ENABLE_SM120:-1}" MOE_ENABLE_SM90="${MOE_ENABLE_SM90:-0}" \
        MOE_BUILD_BATCHGEN=0 TORCH_CUDA_ARCH_LIST="${TORCH_CUDA_ARCH_LIST:-12.0}" \
        MAX_JOBS="${MAX_JOBS:-$(nproc)}" CXX="${CXX:-g++}" \
            $PY benchmarks/expert_placement/build_extensions.py --ext ${EXTS:-_store _cpu_moe}
    )
fi

say "self-checks"
cd "$REPO"
$PY - <<'EOF'
import importlib
for mod, what in (
    ("moe_infinity._store", "MoE-Infinity expert store / fetch path"),
    ("moe_infinity._cpu_moe", "CPU expert kernels"),
):
    try:
        importlib.import_module(mod)
        print(f"  ok      {mod:24s} {what}")
    except Exception as e:  # noqa: BLE001
        print(f"  MISSING {mod:24s} {what}: {e!r}")
for mod in ("sglang", "triton", "matplotlib", "numpy"):
    try:
        m = importlib.import_module(mod)
        print(f"  ok      {mod:24s} {getattr(m, '__version__', '')}")
    except Exception:
        note = " (optional: plots can be made locally)" if mod == "matplotlib" else ""
        print(f"  missing {mod:24s}{note}")
EOF
command -v numactl >/dev/null || say "numactl not installed: run_sweep.sh binds in-process instead"
say "done. In new shells: source $B/env.sh"
